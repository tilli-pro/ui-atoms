export const personName = (rng: Rng): string =>
  `${rng.pick(firstNames)} ${rng.pick(lastNames)}`;

const WHITESPACE = /\s+/;

const slug = (value: string): string =>
  value.toLowerCase().replace(/[^a-z0-9]+/g, "");

/** Lowercase address on an `example.com`-style domain derived from the organization name. */
export const emailFor = (name: string, org: string): string => {
  const [first = "", ...rest] = name.trim().split(WHITESPACE);
  const local = [slug(first), slug(rest.join(" "))].filter(Boolean).join(".");
  const orgSlug = slug(org).slice(0, 24) || "mail";
  return `${local}@${orgSlug}.example.com`;
};

/** Fictional `(555) 010-NNNN` number. */
export const phone = (rng: Rng): string =>
  `(555) 010-${String(rng.int(0, 9999)).padStart(4, "0")}`;

export const address = (rng: Rng): string =>
  `${rng.int(10, 9899)} ${rng.pick(streets)}, ${rng.pick(cities)}`;
