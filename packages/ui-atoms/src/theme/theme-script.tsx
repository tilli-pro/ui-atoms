import type * as React from "react";
import { getThemeScript } from "./script.js";
import type { ThemeConfigOverrides } from "./config.js";

export interface ThemeScriptProps {
  /** The same config the store and `useTheme` get. */
  config?: ThemeConfigOverrides | undefined;
  /** For a Content-Security-Policy that requires one on inline scripts. */
  nonce?: string | undefined;
}

/**
 * Applies the stored theme before first paint. Render it in `<head>`, or as the first
 * child of `<body>`. Renders on the server; it has no client behaviour of its own.
 */
export function ThemeScript({
  config,
  nonce,
}: ThemeScriptProps): React.ReactElement {
  return (
    <script
      // biome-ignore lint/security/noDangerouslySetInnerHtml: the source is generated by getThemeScript, which escapes the config it inlines
      dangerouslySetInnerHTML={{ __html: getThemeScript(config) }}
      nonce={nonce}
      suppressHydrationWarning={true}
    />
  );
}
